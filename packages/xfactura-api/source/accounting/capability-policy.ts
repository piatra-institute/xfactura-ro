export type CapabilityId = keyof typeof capabilityPolicy;
export const agentCapabilities = Object.entries(capabilityPolicy)
  .filter(([id, policy]) => policy.agent && id !== 'capabilities.list')
  .map(([id]) => id as CapabilityId);

export function roleAllows(role: string, permission: Permission) {
  return (
    permission === 'read' || role === 'owner' || (permission !== 'manage' && role === 'reviewer')
  );
}
