CREATE TABLE `acc_income_sources` (
	`company_id` text NOT NULL,
	`source_id` text NOT NULL,
	`seq` integer NOT NULL,
	`effective_from` text NOT NULL,
	`name` text NOT NULL,
	`caen` text NOT NULL,
	`place` text NOT NULL,
	`county` text NOT NULL,
	`authorization_number` text,
	`authorization_date` text,
	`started_on` text NOT NULL,
	`suspended_from` text,
	`suspended_to` text,
	`ended_on` text,
	`liberal` integer NOT NULL,
	`method` text NOT NULL,
	`real_basis` text,
	`evidence_id` text NOT NULL,
	`created_by` text NOT NULL,
	`created_at` text DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')) NOT NULL,
	PRIMARY KEY(`company_id`, `source_id`, `seq`),
	FOREIGN KEY (`company_id`) REFERENCES `acc_companies`(`id`) ON UPDATE no action ON DELETE no action,
	FOREIGN KEY (`created_by`) REFERENCES `user`(`id`) ON UPDATE no action ON DELETE no action,
	FOREIGN KEY (`company_id`,`evidence_id`) REFERENCES `acc_evidence`(`company_id`,`id`) ON UPDATE no action ON DELETE no action,
	CONSTRAINT "income_source_caen" CHECK("acc_income_sources"."caen" glob '[0-9][0-9][0-9][0-9]'),
	CONSTRAINT "income_source_basis" CHECK(("acc_income_sources"."method" = 'norma') = ("acc_income_sources"."real_basis" is null)),
	CONSTRAINT "income_source_liberal" CHECK(not ("acc_income_sources"."liberal" and "acc_income_sources"."method" = 'norma')),
	CONSTRAINT "income_source_dates" CHECK("acc_income_sources"."started_on" <= "acc_income_sources"."effective_from" and ("acc_income_sources"."ended_on" is null or "acc_income_sources"."started_on" <= "acc_income_sources"."ended_on") and ("acc_income_sources"."suspended_to" is null or ("acc_income_sources"."suspended_from" is not null and "acc_income_sources"."suspended_from" <= "acc_income_sources"."suspended_to")))
);
